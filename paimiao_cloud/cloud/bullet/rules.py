"""子弹时间（混合模式里的一种玩法）的规则：纯数据，改这里不用动代码。

## 用户 2026-10-24 定的判据（原话）

> 子弹时间是混合模式里面的，就按降级近战攻击这一行来定吧

也就是：总结页自己那张卡片上出现「降级近战攻击」这一行 → 这一局是子弹时间。
这一行只在子弹时间的总结页出现；普通总结页同一块画面里是「生存时间 / 给予急救次数 /
给予重生次数」那几行，读到的是别的字，所以不会误认（实测 8 张普通/外卡样本全部没命中，
见 docs 里的记录）。

## 为什么坐标要自己算，不能借用上游 crop

上游 `code/ocr.py` 的 `crop()` → `layout.cut()` → `layout.Mapping` 只处理「比 16:9 窄」
（16:10、4:3）的情况：按宽度缩放、上下多出来、多出来的部分按 anchor 分配。
**它不补黑边**：2560×1440（正好 16:9）就是把人家的基准坐标等比放大 4/3。
而实机截图里，1920×1080 的那幅画面放进 2560×1440 屏幕时，四周是有黑边的 ——
我们自己量的结论是左右各空 323、上下各空 182 基准像素（见 RECT 的说明）。
两者差着一个整体平移，框子就落到别的字上去了。

所以这里的框统一按 `RECT` 换算：把基准坐标先平移进黑边、再放大。

## 三块候选，而不是一块

子弹时间那版总结页把「生存时间 / 给予急救次数 / 给予重生次数」三行**整行删掉**了，
下面的行整体上移：同一块坐标在普通版式上读到「生存时间」，在子弹时间版式上读到
「降级近战攻击」（实测 y=515 vs y=543）。

所以不能只加一个框 —— 我们不知道这张总结页是哪一版。做法是**按行位往上找**：
子弹时间那行一定落在某个「普通版式那几行」的上方或原地，按 CANDIDATES 依次读，
第一个读到「降级近战攻击」的就是它。读到一次就记住，这一局不再扫（见 detect.py）。
每条候选都要过一次识别（约 100 毫秒），三块全扫也就 300 毫秒，一局一次。
"""
from __future__ import annotations

# 基准分辨率（和 config/summary.json 的 base_resolution 一致）
BASE_RESOLUTION = [1920, 1080]

# 1920×1080 的画面在实机 2560×1440 截图里占的范围 [左, 上, 宽, 高]（基准像素）。
#
# 2026-10-24 实测结论：**不用补黑边**。一开始以为四周留了黑边（左右 323、上下 182），
# 拿实机截图一验就露馅了 —— 按那样算，候选框整块落到了画面右下角的
# 「继续 / 返回大厅 / 打开菜单」上（见 captures/mode_probe/bt_candidates.png），
# 一块「降级近战攻击」都读不到。改成和上游一样「等比放大、不补黑边」之后，
# 同一张图读 0.9999（这一版是全屏铺满，不是带黑边的窗口）。
#
# 保留这个字段是为了以后遇到真的带黑边的截图（窗口化、缩放模式）时只改一行，
# 不用去动 detect.py。默认就是「铺满」。
RECT = [0, 0, 1920, 1080]

# 判据：这一行字出现在总结页上，就是子弹时间。
LABEL = "降级近战攻击"

# 候选框（基准坐标，[x, y, 宽, 高]，已经按 RECT 换算过的那套）。
#
# 三块都在**中间卡片**（自己的卡片，x 700–1020），y 从「生存时间」那一行往上排：
#   ① [660, 515, 380, 52]  子弹时间实测位置 —— 上面是「造成伤害 / 750」，下面隔一条分割线
#   ② [660, 545, 380, 52]  普通版式「生存时间」行位：读的是「生存时间」，不是我们要的
#   ③ [660, 575, 380, 52]  再往下一格，兜住版式再挤一点的帧
#
# 为什么框 380×52（比上游那几块 180 宽得多）：标签订一共七个字，180 宽只能框到
# 「降级近」；而且 RapidOCR 的检测网络要看到足够上下文才认字（这一点在
# wildcard/rules.py 里也踩过，太窄的一条会返回空）。这里框到 1080 宽处即止，
# 右边就是传奇立绘了（实测 x>1040 开始有立绘，框到 1040 会读到立绘上的杂字）。
CANDIDATES = (
    [660, 515, 380, 52],
    [660, 545, 380, 52],
    [660, 575, 380, 52],
)

# 读到「降级近战攻击」之外，下面那格还应该是个数字（0–999）。
# 用户实测的这张是 0；只要求它是数字，不要求具体值 —— 这一项是辅助，读到标签就算数，
# 所以 MIN_SCORE 只卡标签本身。
MIN_SCORE = 0.9

# 放大倍数（和上游 summary.json 的 upscale 一致）。灰度要**关掉**：
# 上游开灰度是为了让橙色数字的斜杠不被读成 1，我们这里是灰色小字标签，
# 实测彩色 0.9999、灰度 0.995，彩色更好。
UPSCALE = 2
GRAYSCALE = False

# 库里的模式键。**和 lobby_mode（大厅识别）用同一个**：那边已经把
# 「混合模式·控制 / 子弹时间 / 团队死斗」按大厅卡片读出来了，子弹时间记成
# mixed_bullet_time（见 cloud/lobby_mode/rules.py 的 MODE_TITLES / MODE_LABELS）。
# 2026-10-24 用户拍板：总结页认出来的也写这个键，不另造一个 bullet。
#
# 页面上的名字用上游 MODES 里现成的（lobby_mode 注入进去的）：
#     mixed_bullet_time → 混合模式·子弹时间
MODE_KEY = "mixed_bullet_time"
MODE_LABEL = "子弹时间"

# 详情页里这一行数字的名字（外卡是「自我急救 / 最后幸存」，子弹时间是这一行）。
MELEE_LABEL = "降级近战攻击"


def ocr_cfg():
    """给上游 `ocr.crop` 用的最小配置（它只认这三个键）。"""
    return {"base_resolution": BASE_RESOLUTION, "upscale": UPSCALE, "grayscale": GRAYSCALE}
