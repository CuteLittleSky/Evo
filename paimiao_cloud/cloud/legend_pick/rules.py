def outline(gray):
    """灰度图 → 笔画边缘（亮字在暗底上：减掉模糊后的自己，剩下的就是边缘）。"""
    gray = gray.astype("float32")
    blurred = cv2.GaussianBlur(gray, (0, 0), OUTLINE_SIGMA)
    return cv2.subtract(gray, blurred)


def search_region(frame, roi, anchor=None):
    """从截图上裁出第 roi 条的搜索区（含 SEARCH_PAD 余量），缩到基准大小，返回轮廓图。

    先缩到基准大小**再**取轮廓：理由见文件开头"踩过的坑"。裁不到时返回 None。

    `anchor` 是这块界面在多出来的高度里靠上还是居中。**不靠猜**：`anchor_scores` 会把
    两种都试一遍取高的那个 —— 16:10 / 4:3 时这两种差 120 像素，猜错就整条认不出
    （实测猜 "top" 而实际居中时 0.07，反过来 0.80）。
    """
    from layout import cut          # noqa: PLC0415  上游的裁切

    pad = SEARCH_PAD
    box = [roi[0] - pad, roi[1] - pad, roi[2] + 2 * pad, roi[3] + 2 * pad]
    crop = cut(frame, box, BASE, anchor or ANCHOR)
    if crop is None or crop.size == 0 or crop.shape[0] < 8 or crop.shape[1] < 8:
        return None
    gray = cv2.cvtColor(crop, cv2.COLOR_BGR2GRAY)
    gray = cv2.resize(gray, (box[2], box[3]), interpolation=cv2.INTER_AREA)
    return outline(gray)


def match(frame, roi, ref):
    """frame 上第 roi 条提示和参照图 ref 的最高相似度（0~1）。裁不到返回 0。

    ref 是轮廓图（同 outline 出来的），要比的图两边都统一转 float32：
    cv2.matchTemplate 要求图和参照的深度一致，混着给会直接抛错。
    """
    import cv2 as _cv2            # noqa: PLC0415  只在这个模块用到

    if ref is None:
        return 0.0
    best = 0.0
    for anchor in ANCHORS:
        region = search_region(frame, roi, anchor)
        if region is None:
            continue
        if region.shape[0] < ref.shape[0] or region.shape[1] < ref.shape[1]:
            continue
        try:
            found = _cv2.matchTemplate(region.astype("float32"), ref.astype("float32"),
                                       _cv2.TM_CCOEFF_NORMED)
            value = float(found.max())
        except Exception:
            continue
        if value > best:
            best = value
    return best
