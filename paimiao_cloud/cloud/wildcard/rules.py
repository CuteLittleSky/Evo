"""外卡模式的规则（纯数据，改这里不用动代码）。

坐标全部是**基准分辨率 1920×1080 下的像素**，换算、裁图、放大都交给上游
`code/ocr.py` 的 `crop(img, roi, cfg, anchor)` —— 它已经处理了 2560×1440、
16:10、4:3 这些情况（见 `code/layout.py`），我们自己再算一遍只会多一种错法。

## 为什么这两行标签就是外卡

总结页每人卡片左下半段是五行，普通模式和外卡模式**坐标完全一样**，只有标签不同：

    普通： 生存时间 / 给予急救次数 / 给予重生次数
    外卡： 生存时间 / 最后幸存     / 自我急救

用户 2026-10-24 的要求：「识别到了"自我急救"和"最后幸存"就是外卡」。
数字（急救次数、重生次数）仍然由上游照常读，这两行只用来认模式。

## 框怎么量的

2026-10-24 在用户给的实机截图上量的（`captures/live/20261024_160229/01_161121.png`，
2560×1440）。先说一个踩过的坑：**别自己从截图里量坐标**。

一开始我按「卡片左上角 + 行序号」去推，把截图像素直接当成基准像素，还丢了 `anchor: center`
的偏移，框全落到了别人的卡片和插画上 —— 三次测试全是「没读到」，看起来像识别不出来。
正确做法是**借用上游已经校准过的那两块**（revives / respawns），往上收一下就成了：

    上游 revives   [748, 613, 180, 40]  ← 标签『给予急救次数』+ 数字，两行都在里头
    上游 respawns  [748, 683, 180, 40]

    我们的 revive   [748, 596, 180, 22]  ← 只留标签那一行
    我们的 respawn  [748, 666, 180, 22]

已实测（三张实机总结页）：19 行高度下都 1.00 认出「给予急救次数」；
32 行高（[748,608,180,32]）会把「给」的竖钩和下面的「1」连成一个字，所以**只能用 22**。

坐标基准 1920×1080，送进 `ocr.crop` 时会按 `anchor: center` 自动换算到 2560×1440。
"""
from __future__ import annotations

# 基准分辨率（和 config/summary.json 的 base_resolution 一致）
BASE_RESOLUTION = [1920, 1080]

# 外卡标签所在的框（1920×1080 基准；OCR 实测见 docs 里的记录）。
#
# 为什么不能只框那 4 个字的标签行：2026-10-24 实测，只给一行字的窄条
# （[748,666,180,22] 之类）引擎返回**空结果**——RapidOCR 的检测网络要看到足够的上
# 下文才认字。而把 [700,560,320,160] 这块（含上一行时间和下面两个数字）整个丢进去，
# 「最后幸存」「自我急救」都是 1.00。所以按「一小块画面」来框，读到的东西再挑：
# 只认那两条标签文字，数字、时间一概不管。
#
# 一行是同一块：上面「最后幸存」、下面「自我急救」，卡片的 x 起点 ~700，
# 两行都在 y 560–740 之间；右边的传奇立绘从这里开始，往右取到 1020 已经不碰到。
# 高度取到 180（含上一行「生存时间」）：实测 560+180 能稳定读出「最后幸存」，
# 只取 160 时同一帧读不出上一行的时间，OCR 会把它和别的行挤在一起。
LABEL_ROI = [700, 560, 320, 180]

# 一行一条：认出来就算命中（两条都认出来最好）
WILDCARD_LABELS = (
    {"name": "wildcard_respawn", "text": "最后幸存"},
    {"name": "wildcard_revive", "text": "自我急救"},
)

# 读到任意一条就认定是外卡。两条都读到最好，但只读到一条也够 ——
# 这行字只在总结页出现，普通模式这里是「给予急救次数」，不会误认。
MIN_HITS = 1

# 置信度下限。和上游 summary.json 的 min_score 一致：标签只有四个字，
# 实测置信度都在 0.9 以上，用门槛挡掉噪声，宁可空着也不猜。
MIN_SCORE = 0.9

# 页面上的叫法（和游戏里的字一致；上游 code/panel_app.py 的 MODES 里没有这个键，
# 由 page.py 注入进去）。
MODE_KEY = "wildcard"
MODE_LABEL = "外卡"

# 外卡局那两行数据的名字。普通局沿用上游原来的字（上游模板里写死的），外卡局用游戏里的字。
REVIVE_LABEL = "自我急救"
RESPAWN_LABEL = "最后幸存"


def label(kind: str, wildcard: bool) -> str:
    """页面上的数据名。kind: "revive"（急救次数）/ "respawn"（重生次数）。

    返回 None 表示「沿用上游模板里原来写死的字」，也就是普通局什么也不用改。
    """
    if not wildcard:
        return None
    return REVIVE_LABEL if kind == "revive" else RESPAWN_LABEL

